// 직전에 보여준 문구와 연달아 같은 문구가 뜨지 않도록 하는 랜덤 선택 함수.
// localStorage에 마지막으로 보여준 인덱스를 저장해, 새로고침/탭 이동 후에도 중복을 피한다.
const LAST_QUOTE_KEY = 'bodytailor-last-quote-idx'

export function pickRandomQuote() {
  if (HOME_QUOTES.length === 0) return ''
  let lastIdx = -1
  try {
    lastIdx = Number(window.localStorage.getItem(LAST_QUOTE_KEY))
  } catch {
    lastIdx = -1
  }
  let idx = Math.floor(Math.random() * HOME_QUOTES.length)
  if (HOME_QUOTES.length > 1) {
    while (idx === lastIdx) {
      idx = Math.floor(Math.random() * HOME_QUOTES.length)
    }
  }
  try {
    window.localStorage.setItem(LAST_QUOTE_KEY, String(idx))
  } catch {
    // localStorage 접근 불가 환경(사파리 프라이빗 모드 등)이면 중복 방지 없이 그냥 랜덤만 적용
  }
  return HOME_QUOTES[idx]
}
