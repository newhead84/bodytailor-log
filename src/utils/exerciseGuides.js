export function getEquipment(name, atom) {
  const n = String(name)
  if (EQUIPMENT_OVERRIDE[n]) return EQUIPMENT_OVERRIDE[n]
  if (atom === '유산소') return '유산소 기구'
  if (/밴드/.test(n)) return '밴드'
  if (/스미스/.test(n)) return '스미스머신'
  if (/케이블|페이스풀|푸시다운/.test(n)) return '케이블'
  if (/머신|펙덱|레그프레스|레그익스텐션|레그컬|어브덕션|어덕션|어시스트/.test(n)) return '머신'
  if (/덤벨|고블릿|원레그데드/.test(n)) return '덤벨'
  if (/바벨|이지바|T바|JM|클로즈그립|굿모닝|데드리프트|백스쿼트|프론트스쿼트/.test(n)) return '바벨'
  if (/플레이트/.test(n)) return '원판'
  return '맨몸'
}
