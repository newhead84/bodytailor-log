def clean(v,k):
  if pd.isna(v): return None
  return round(float(v),1) if k!='kcal' and k!='na' else round(float(v))
def pick(df,code,label):
  m=df[df['식품코드']==code]
  assert len(m)>=1, code
  r=m.iloc[0]
  assert r['영양성분함량기준량']=='100g', (code, r['영양성분함량기준량'])
  return {k:clean(r[v],k) for k,v in C.items()}, f"{code} {r['식품명']}"
def med(rep,name,ex=None,minP=None,unit='100g'):
  m=P[(P['영양성분함량기준량']==unit)&P['대표식품명'].str.contains(rep,na=False,regex=True)&P['식품명'].str.contains(name,na=False,regex=True)]
  if ex: m=m[~m['식품명'].str.contains(ex,na=False,regex=True)]
  if minP: m=m[m['단백질(g)']>=minP]
  m=m.dropna(subset=['에너지(kcal)','단백질(g)'])
  assert len(m)>=5, (rep,name,len(m))
  vals={k:clean(m[v].median(),k) for k,v in C.items()}
  return vals, f"가공식품 {len(m)}개 제품 중앙값({rep} · {name})"
